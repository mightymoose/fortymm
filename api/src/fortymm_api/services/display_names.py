_ADJECTIVES_BY_INITIAL: dict[str, tuple[str, ...]] = {
    initial: tuple(word for word in ADJECTIVES if word[0] == initial)
    for initial in {word[0] for word in ADJECTIVES}
}


def random_display_name() -> str:
    animal = secrets.choice(ANIMALS)
    adjective = secrets.choice(_ADJECTIVES_BY_INITIAL[animal[0]])
    return f"{adjective} {animal} {100 + secrets.randbelow(900)}"
