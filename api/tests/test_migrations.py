import subprocess
import sys
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, MetaData, Table, text

from fortymm_api.database import create_database_engine
from fortymm_api.models import Base

API = Path(__file__).parent.parent
# Test revisions in place of the real ones, run by the real env.py.
REVISIONS = Path(__file__).parent / "revisions"

# Alembic keeps its context in module globals, so two threads would share
# one. Separate processes upgrade as two API instances would.
UPGRADE_IN_A_PROCESS = """
import sys
from alembic import command
from alembic.config import Config
from fortymm_api.database import create_database_engine

url, revisions = sys.argv[1:]
config = Config("alembic.ini")
config.set_main_option("version_locations", revisions)
engine = create_database_engine(url)
with engine.connect() as connection:
    config.attributes["connection"] = connection
    command.upgrade(config, "head")
"""


@contextmanager
def connected(url: str, revisions: Path | None = None) -> Iterator[Config]:
    config = Config(API / "alembic.ini")
    if revisions is not None:
        config.set_main_option("version_locations", str(revisions))
    engine = create_database_engine(url)
    try:
        with engine.connect() as connection:
            config.attributes["connection"] = connection
            yield config
    finally:
        engine.dispose()


def upgrade(url: str, revisions: Path | None = None) -> None:
    with connected(url, revisions) as config:
        command.upgrade(config, "head")


def applied(url: str) -> tuple[list[str], str | None]:
    """Each revision's run, in order, and the version Alembic recorded."""
    engine = create_database_engine(url)
    try:
        with engine.connect() as connection:
            runs = connection.scalars(text("SELECT revision FROM applied"))
            version = connection.scalar(text("SELECT version_num FROM alembic_version"))
            return list(runs), version
    finally:
        engine.dispose()


def test_concurrent_upgrades_apply_each_revision_once(
    throwaway_database_url: str,
) -> None:
    upgrades = [
        subprocess.Popen(
            [
                sys.executable,
                "-c",
                UPGRADE_IN_A_PROCESS,
                throwaway_database_url,
                str(REVISIONS),
            ],
            cwd=API,
            stderr=subprocess.PIPE,
            text=True,
        )
        for _ in range(2)
    ]
    errors = [upgrade.communicate(timeout=60)[1] for upgrade in upgrades]

    assert [upgrade.returncode for upgrade in upgrades] == [0, 0], errors
    assert applied(throwaway_database_url) == (["first", "second"], "second")


def test_a_second_upgrade_applies_nothing(throwaway_database_url: str) -> None:
    upgrade(throwaway_database_url, REVISIONS)
    upgrade(throwaway_database_url, REVISIONS)

    assert applied(throwaway_database_url) == (["first", "second"], "second")


def test_check_passes_when_the_models_match_the_migrations(
    throwaway_database_url: str,
) -> None:
    upgrade(throwaway_database_url)

    with connected(throwaway_database_url) as config:
        config.attributes["target_metadata"] = Base.metadata
        command.check(config)


def test_check_fails_on_a_model_change_without_a_revision(
    throwaway_database_url: str,
) -> None:
    upgrade(throwaway_database_url)
    changed = MetaData(naming_convention=Base.metadata.naming_convention)
    for table in Base.metadata.tables.values():
        table.to_metadata(changed)
    Table("clubs", changed, Column("id", Integer, primary_key=True))

    with connected(throwaway_database_url) as config:
        config.attributes["target_metadata"] = changed
        with pytest.raises(AutogenerateDiffsDetected) as diffs:
            command.check(config)
    assert "add_table" in str(diffs.value)
    assert "clubs" in str(diffs.value)


def test_an_account_with_the_first_administrators_email_gets_the_role(
    throwaway_database_url: str,
) -> None:
    with connected(throwaway_database_url) as config:
        command.upgrade(config, "e88c34e67214")
        connection = config.attributes["connection"]
        connection.execute(
            text("INSERT INTO accounts (email) VALUES ('mightymoose@fortymm.com')")
        )
        connection.commit()
        command.upgrade(config, "head")
        connection.commit()

        held = connection.execute(
            text(
                "SELECT accounts.email, roles.name FROM account_roles"
                " JOIN accounts ON accounts.id = account_id"
                " JOIN roles ON roles.id = role_id"
            )
        ).all()
        grants = connection.scalar(text("SELECT count(*) FROM email_role_grants"))

    assert held == [("mightymoose@fortymm.com", "Administrator")]
    assert grants == 0
