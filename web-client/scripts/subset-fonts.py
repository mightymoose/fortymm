"""Split the design system's Bebas Neue and JetBrains Mono into woff2 files
by unicode-range, the way space-grotesk.css splits Space Grotesk, and write a
stylesheet for each font. A page then downloads only the files its text uses.

The files come from the reference's own TTFs, which the reference kit embeds,
so the screenshot tests compare the same glyph outlines.

    uv run web-client/scripts/subset-fonts.py
"""

from dataclasses import dataclass
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = ROOT / "references/deprecated/fortymm-design-system/fonts"
OUT_DIR = ROOT / "web-client/src/assets/fonts"


@dataclass(frozen=True)
class Font:
    family: str
    source: str
    stem: str
    weight: str
    format: str


FONTS = [
    Font("Bebas Neue", "BebasNeue-Regular.ttf", "BebasNeue-Regular", "400", "woff2"),
    Font(
        "JetBrains Mono",
        "JetBrainsMono-VariableFont_wght.ttf",
        "JetBrainsMono-VariableFont_wght",
        "100 800",
        "woff2-variations",
    ),
]

# Fontsource's ranges, a superset of the ones space-grotesk.css uses. A
# font's characters outside all of them go in an "other" file.
SUBSETS = {
    "cyrillic-ext": "U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F",
    "cyrillic": "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116",
    "greek": "U+0370-0377,U+037A-037F,U+0384-038A,U+038C,U+038E-03A1,U+03A3-03FF",
    "vietnamese": "U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB",
    "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
}


def parse_range(unicode_range: str) -> set[int]:
    codepoints: set[int] = set()
    for part in unicode_range.split(","):
        start, _, end = part.removeprefix("U+").partition("-")
        codepoints.update(range(int(start, 16), int(end or start, 16) + 1))
    return codepoints


def format_range(codepoints: set[int]) -> str:
    runs: list[tuple[int, int]] = []
    for cp in sorted(codepoints):
        if runs and runs[-1][1] == cp - 1:
            runs[-1] = (runs[-1][0], cp)
        else:
            runs.append((cp, cp))
    return ",".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in runs)


def write_subset(source: Path, codepoints: set[int], out: Path) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(out)


def font_face(font: Font, file: str, unicode_range: str) -> str:
    return f"""@font-face {{
  font-family: '{font.family}';
  src: url('./{file}') format('{font.format}');
  font-weight: {font.weight};
  font-style: normal;
  font-display: swap;
  unicode-range: {unicode_range};
}}
"""


def main() -> None:
    for font in FONTS:
        source = SOURCE_DIR / font.source
        covered = set(TTFont(source).getBestCmap())
        ranges = {name: parse_range(r) for name, r in SUBSETS.items()}
        other = covered - set().union(*ranges.values())
        if other:
            ranges = {"other": other, **ranges}
        faces = []
        for name, codepoints in ranges.items():
            if not codepoints & covered:
                continue
            file = f"{font.stem}-{name}.woff2"
            write_subset(source, codepoints & covered, OUT_DIR / file)
            unicode_range = format_range(other) if name == "other" else SUBSETS[name]
            faces.append(font_face(font, file, unicode_range))
        css = OUT_DIR / f"{font.family.lower().replace(' ', '-')}.css"
        css.write_text(
            f"/* {font.family}, split by unicode-range from the design system's\n"
            f"   fonts/{font.source}. Generated by web-client/scripts/subset-fonts.py. */\n\n"
            + "\n".join(faces)
        )
        print(f"wrote {css.relative_to(ROOT)} ({len(faces)} files)")


if __name__ == "__main__":
    main()
