import { tanstackRouter } from '@tanstack/router-plugin/vite'
import react from '@vitejs/plugin-react'
import { msw } from 'msw/vite'
import { searchForWorkspaceRoot } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'
import { defineConfig } from 'vitest/config'

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    // Must come before react().
    tanstackRouter({ target: 'react', autoCodeSplitting: true }),
    react(),
    // The dev server's api mocks (see src/main.tsx). Serves msw's worker script on the dev server, and
    // emits it into a build only if the build imports `virtual:msw`, which ours never does.
    msw(),
    // Offline: a Workbox service worker, generated by `vite build` only (the dev server has msw's
    // worker instead).
    // It precaches the whole build, so the app loads with no network, and serves index.html for
    // every client-side route. A new build's worker waits (prompt) until the user presses Reload on
    // the toast that AppUpdate shows (src/components/AppUpdate.tsx), so an open tab never runs old
    // code against a new precache.
    VitePWA({
      registerType: 'prompt',
      manifest: false,
      workbox: {
        // The first install controls the open page at once (so it works offline from the first
        // visit). An update only activates when Reload asks it to, so this never swaps code under it.
        clientsClaim: true,
        globPatterns: ['**/*.{html,js,css,svg,ttf,woff2,wasm}'],
        navigateFallback: '/index.html',
        // The api is always the network's: a navigation to it is never the app.
        navigateFallbackDenylist: [/^\/api\//],
      },
    }),
  ],
  // Runs in a container (see docker-compose.yml): listen on all interfaces at a fixed
  // container port. Docker maps it to a random host port.
  server: {
    host: true,
    port: 5173,
    strictPort: true,
    // The verify task's e2e tests reach it on the compose network as http://web-client:5173.
    allowedHosts: ['web-client'],
    // The api serves its routes under /api, so requests pass through unchanged. It is the `api`
    // service on the compose network. (The nginx build proxies it itself: see nginx.conf.template.)
    proxy: {
      '/api': 'http://api:8000',
    },
    // fortymm-core-wasm is a file: link to ../core/bindings/wasm/pkg, outside the project, so its
    // .wasm (fetched by init()) would be refused without this.
    fs: {
      allow: [searchForWorkspaceRoot(process.cwd()), '../core/bindings/wasm/pkg'],
    },
  },
  // `vite preview` serves a build for the e2e tests (see playwright.config.ts). It takes the dev
  // server's host, allowed hosts and /api proxy; only the port has its own default.
  preview: {
    port: 5173,
  },
  // Unit tests (Vitest) sit next to the code they test as *.test.ts(x); e2e/ is Playwright's.
  test: {
    environment: 'jsdom',
    include: ['src/**/*.test.{ts,tsx}'],
    setupFiles: ['./src/setupTests.ts'],
  },
})
